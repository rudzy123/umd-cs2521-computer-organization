#!/usr/bin/env python3
"""Write an objdump listing of the laboratory's assembly objects.

objdump prints one column of section offsets, one column of machine-code
bytes, and one column of AT&T mnemonics. Those offsets belong to the
relocatable object file. They are not addresses from a running process.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HEADER = """\
CS 2521 example disassembly
Generated by scripts/disassemble.py using objdump -d.
Addresses are section offsets inside relocatable object files, not runtime
load addresses. The mnemonics use AT&T syntax, the same syntax as assembly/*.S.

Columns, from the left:
  section offset
  machine-code bytes
  mnemonic and operands

"""


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: disassemble.py BUILD_DIR OUTPUT", file=sys.stderr)
        return 2
    build = Path(argv[1])
    output = Path(argv[2])
    objects = sorted(path for path in build.rglob("*.o") if "assembly" in path.parts)
    if not objects:
        print(f"no assembly objects under {build}", file=sys.stderr)
        return 1

    chunks = [HEADER]
    for obj in objects:
        completed = subprocess.run(
            ["objdump", "-d", str(obj)],
            check=False,
            capture_output=True,
            text=True,
        )
        if completed.returncode != 0:
            sys.stderr.write(completed.stderr)
            return completed.returncode
        listing = completed.stdout.replace(str(obj.resolve()), obj.name)
        listing = listing.replace(str(obj), obj.name)
        chunks.append(listing.rstrip() + "\n")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(chunks), encoding="utf-8")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
